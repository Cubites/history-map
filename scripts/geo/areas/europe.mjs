// ── 조각 소유표의 틀 (작업 E2, 2026-10-02 작업 E3에서 시대별 표 여러 개로 넓힘) ─────────────
// 단위: 조각 하나를 통째로 쓰면 그 조각 id, 선으로 나눴으면 '이름/부분'. own(단위들, [[해, 나라], ...])는 그 해부터 다음 해 전까지 그 나라 땅이라는 뜻이다.
// 나라가 null이면 일부러 비워 둔 땅(주인 없는 땅·이 지도에 없는 나라의 땅)이고, 빈 땅 검사 구역에서 그 해에 뺀다(맨 아래 gapZones).
// 소유표는 시대마다 하나다: '1815~1914 조각 소유표'(작업 E2, T1815)와 '1789~1814 조각 소유표'(작업 E3, T1789). 표마다 모든 조각을 정확히 한 번 쓰고,
// 조각을 나누는 선은 표마다 달라도 된다. 단위 이름과 도형은 표 사이에서 함께 쓴다: 다른 표에서 나눈 조각을 같은 선으로 쓰려면 reuse(나눈 조각)로 가져오고,
// 같은 단위 이름을 다른 도형으로 다시 정의하면 멈춘다(통째 조각은 이름 = 조각 id라 어느 표에서나 같다).
// 이웃한 두 표에서 한 나라의 단위 목록이 같으면 한 버전으로 잇는다(예: 에스파냐는 1814년 버전이 1815년 뒤로 이어짐).
// renames: 나라 이름(항목)만 바뀌고 땅은 그대로 넘어간 해. 그 해부터 그 나라의 모든 단위 주인을 새 항목으로 바꿔 읽는다(줄마다 되풀이해 적지 않으려고).
// 나라별 마지막 버전은 TAIL_TO(그 뒤 첫 국경 변화 해)까지 이어 쓴다. 1914년은 7월(1차 대전 직전) 모습이다.
const unitMake = new Map(); // 단위 이름 → null(통째 조각) 또는 도형을 만드는 함수 (모든 표가 함께 씀)
const splitIds = new Map(); // split이 돌려준 단위 이름 객체 → 그 묶음의 조각 id (reuse가 씀)
const makeTable = (FROM, TO, renames = {}) => {
  const label = `${FROM}~${TO - 1} 소유표`;
  const claimed = new Map(); // 조각 id → 그 조각을 쓴 단위·묶음 이름 (이 표 안)
  const used = new Set(); // 이 표가 쓰는 단위
  const ownership = new Map(); // 단위 → [[해, 나라|null], ...]
  const claim = (id, by) => {
    if (!EU.props.has(id)) throw new Error(`europe.mjs ${label}: 모르는 조각 id ${id}`);
    if (claimed.has(id)) throw new Error(`europe.mjs ${label}: 조각 ${id}를 ${claimed.get(id)}와 ${by}에서 함께 씀`);
    claimed.set(id, by);
  };
  const use = (name) => {
    if (used.has(name)) throw new Error(`europe.mjs ${label}: 단위 이름 ${name}이 겹침`);
    used.add(name);
  };
  const define = (name, make) => {
    if (unitMake.has(name) && (make !== null || unitMake.get(name) !== null)) {
      throw new Error(`europe.mjs ${label}: 단위 이름 ${name}을 다시 정의함 (다른 표에서 나눈 조각을 쓰려면 reuse)`);
    }
    unitMake.set(name, make);
  };
  // 통째 조각. 단위 이름 = 조각 id
  const whole = (...ids) => {
    for (const id of ids) {
      claim(id, id);
      use(id);
      define(id, null);
    }
    return ids;
  };
  // 나눈 조각: 조각 묶음 ids를 parts의 도형으로 차례로 자른다. 첫 부분 = I(F(ids), 도형1), 둘째 = I(D(F(ids), 도형1), 도형2), …, 나머지 = D(F(ids), 도형1, 도형2, …).
  // 부분들이 묶음을 빈틈·겹침 없이 나눈다. 반환: 단위 이름 객체 { 부분 이름: '묶음/부분' }
  const split = (name, ids, parts, restName) => {
    for (const id of ids) claim(id, name);
    const out = {};
    const shapes = [];
    for (const [part, shape] of parts) {
      const before = [...shapes];
      out[part] = `${name}/${part}`;
      use(out[part]);
      define(out[part], () => I(before.length ? D(F(...ids), ...before) : F(...ids), shape));
      shapes.push(shape);
    }
    out[restName] = `${name}/${restName}`;
    use(out[restName]);
    define(out[restName], () => D(F(...ids), ...shapes));
    splitIds.set(out, ids);
    return out;
  };
  // 다른 표에서 나눈 조각을 이 표에서도 같은 선(같은 단위)으로 쓴다
  const reuse = (out) => {
    const ids = splitIds.get(out);
    if (!ids) throw new Error(`europe.mjs ${label}: reuse에는 split이 돌려준 객체를 준다`);
    for (const id of ids) claim(id, Object.values(out)[0]);
    for (const name of Object.values(out)) use(name);
    return out;
  };
  const own = (list, timeline) => {
    if (timeline[0]?.[0] !== FROM || timeline.some(([y], i) => !Number.isInteger(y) || (i && y <= timeline[i - 1][0]) || y >= TO)) {
      throw new Error(`europe.mjs ${label}: ${list[0]} 등의 기간 ${JSON.stringify(timeline)} (첫 해는 ${FROM}, 해는 늘어나고 ${TO} 전)`);
    }
    for (const u of list) {
      if (!used.has(u)) throw new Error(`europe.mjs ${label}: 이 표에서 정의하지 않은 단위 ${u}`);
      if (ownership.has(u)) throw new Error(`europe.mjs ${label}: 단위 ${u}의 주인을 두 번 적음`);
      ownership.set(u, timeline);
    }
  };
  // 표 검사(모든 조각을 정확히 한 번 썼는지, 모든 단위에 주인을 적었는지) 뒤 해마다 [해, 나라|null, 단위 목록]
  const finish = () => {
    const unused = EU.ids.filter((id) => !claimed.has(id));
    if (unused.length) throw new Error(`europe.mjs ${label}: 쓰지 않은 조각 ${unused.length}개 (${unused.slice(0, 10).join(', ')} …)`);
    const ownerless = [...used].filter((u) => !ownership.has(u));
    if (ownerless.length) throw new Error(`europe.mjs ${label}: 주인을 적지 않은 단위 ${ownerless.join(', ')}`);
    const ownerAt = (timeline, year) => {
      const owner = timeline.filter(([y]) => y <= year).at(-1)[1];
      const rename = renames[owner];
      return rename && year >= rename[0] ? rename[1] : owner;
    };
    const rows = [];
    for (let year = FROM; year < TO; year++) {
      const byOwner = new Map();
      for (const [u, timeline] of ownership) {
        const owner = ownerAt(timeline, year);
        if (!byOwner.has(owner)) byOwner.set(owner, []);
        byOwner.get(owner).push(u);
      }
      for (const [owner, list] of byOwner) rows.push([year, owner, list.sort()]);
    }
    return rows;
  };
  return { FROM, TO, whole, split, reuse, own, finish };
};

