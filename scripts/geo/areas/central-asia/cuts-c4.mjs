//   반환: [[부분 이름, 도형], …, ['동', 남은 땅]] (처음 부를 때 한 번 계산)
import { XJ as C4E_XJ } from './table.mjs';
import { deg2 as C4E_deg2 } from './prev.mjs';
let C4E_partsMemo = null;
export const C4E_xjParts = () => {
  if (C4E_partsMemo) return C4E_partsMemo;
  const noDust = (m) => m.filter((p) => C4E_deg2([p]) >= 1e-6);
  let left = C4E_XJ.filter((p) => C4E_deg2([p]) >= 0.03);
  const parts = [];
  for (const [name, shape] of C4E_XJ_SHAPES) {
    const got = noDust(I(left, shape));
    const keep = got.length > 1 ? got.filter((q) => C4E_deg2([q]) >= 0.03) : got;
    const crumbs = got.filter((q) => !keep.includes(q));
    parts.push([name, keep]);
    left = noDust(D(left, shape));
    if (crumbs.length) left = U(left, crumbs);
  }
  parts.push(['동', left]);
  C4E_partsMemo = parts;
  return parts;
};
