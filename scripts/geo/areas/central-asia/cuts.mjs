export const A_clip = new Map(); // 칸 땅 도형 → (앞 권역 도형(prevMinusOf가 돌려준 잘린 도형) → 그 땅으로 자른 도형)
export const A_prevAt = (y, dom) => {
  if (!A_clip.has(dom)) A_clip.set(dom, new Map());
  const memo = A_clip.get(dom);
  return prevMinusOf(y, y + 1).map((g) => {
    if (!memo.has(g)) memo.set(g, I(g, dom));
    return memo.get(g);
  }).filter((g) => g.length);
};
// [from, to) 동안 dom(칸 땅의 한쪽) 안 앞 권역 도형. 그 사이 넓이가 바뀌면 멈춤
export const A_prevSpan = (from, to, dom) => {
  const first = A_prevAt(from, dom);
  const size = first.reduce((t, g) => t + deg2(g), 0);
  for (let y = from + 1; y < to; y++) {
    const s = A_prevAt(y, dom).reduce((t, g) => t + deg2(g), 0);
    if (Math.abs(s - size) > 1e-4) throw new Error(`central-asia cuts.mjs A: ${from}~${to - 1} 안 ${y}년에 이 칸 땅의 앞 권역 도형이 바뀜(${size.toFixed(5)} → ${s.toFixed(5)}제곱도) — A_BOUNDS·묶음 기간을 나눈다`);
  }
  return first.length ? U(...first) : [];
};
export const A_minus = (g, p) => (p.length ? D(g, p) : g);
