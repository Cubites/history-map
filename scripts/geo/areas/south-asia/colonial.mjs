// 운영자 결정(00-scope 10절): 1만 km² 이상 토후국은 따로 항목(vassal_of 종주: 1858년 전 company-india, 1858년부터 british-raj), 1만 km² 미만이 이어져 1만 km² 넘는 곳은
//   '○○ 토후국들' 묶음 항목, 그 밖은 종주 색. 식민 본국은 넓히지 않고 따로 항목. 버마는 그리지 않음(동남아 몫). 아프가니스탄 쪽은 권역 바깥.
// 표: modern.mjs와 같은 꼴의 조각 소유표(table.mjs). tableKit('colonial')로 자기 꾸러미를 받아 단위 이름이 다른 시대 파일과 부딪치지 않는다.
//   표는 하나다(1757~1946). 조각은 남아시아 조각(loadFragments('south-asia'))을 그대로 쓰고 새로 만들지 않는다. 옛 경계는 칼선으로 나눈다.
//   마지막 해(미포함)는 S2_END(1947) = modern.mjs의 첫 해. 1947년에도 이어지는 S1 항목(nepal·bhutan·sikkim·hyderabad-state·kalat 등)은 같은 id를 주인으로 쓰면
//   joinEras가 modern.mjs의 1947년부터 버전 앞에 붙인다(권역 파일 시대 목록이 [colonialEra, modernEra]로 과거가 앞). 1946년 줄은 modern.mjs 1947년 줄과 견준다.
// 해 줄 넣는 법: own(단위들, [[해, 주인], …]), 나눈 조각은 ownSplit(묶음 이름, 조각 id들, [[부분, 칼선 도형], …], 나머지 이름, { 부분: 줄 }).
//   주인 null은 비운 땅(이유는 voids에 한 줄). 첫 줄의 첫 해는 S2_START(1757). 줄을 적지 않은 단위는 맨 아래 fillTables가 시대 내내 주인 null로 채운다.
//   한 조각을 기간에 따라 다르게 나누려면 ownSplit의 마지막 인자 { from, to }(표 경계 해만 — 표가 하나이므로 지금은 1757·1947뿐).
//   그래서 한 조각의 칼선은 시대 내내 같은 묶음 하나다. 해마다 다른 경계는 부분을 여럿 두고 부분마다 줄을 달리 적는다.
// 칸 나눔(부딪침 막기, <sp>/IMPL-SPLIT.md): 구현 S2-서는 '── S2 서 ──' 칸, S2-동은 '── S2 동 ──' 칸, S2-남은 '── S2 남 ──' 칸 아래에만 쓴다(칼선·상수·own 줄·voids 줄 모두).
//   같은 조각을 두 칸이 own하지 않는다(own이 같은 단위의 두 번째 줄을 '이은 줄'로 받아 해가 겹치면 멈춤). 최상위 이름은 칸마다 앞머리: 서 W_, 동 E_, 남 S_.
//   칸 밖 공통 줄은 cnMinusOf 한 줄(동 칸만 고침) 말고는 고치지 않는다.
// 늘린 나라: 소유표의 주인으로 다른 권역 나라 id를 쓰려면 권역 파일 extendable에 있어야 한다(운영자 승인 줄만, 00-scope 5절).
// 월경지·허용 줄·정답표·표기 사전·relations는 각 파일 끝(그 파일의 남아시아 절 끝)에 자기 머리 줄('# ── 남아시아 S2 서 …' 등)을 두고 그 아래에만.
// 가져오기: 아래 두 줄은 공통이다. 각 칸이 더 가져올 것은 자기 칸 머리에 import 줄을 따로 둔다(import는 모듈 맨 위로 끌어올려지므로 칸 안에 두어도 된다)
import { D } from '../../lib.mjs';
import { SA, tableKit } from './table.mjs';

const { build, joinTables, makeTable } = tableKit('colonial');

const S2_START = 1757; // 이 시대 파일의 첫 해: 플라시 전투(1757-06-23) 해 말
const S2_END = 1947; // 이 시대 파일의 끝(미포함) = modern.mjs의 첫 해

// ── 조각 소유표 도우미 (서아시아 orient.mjs와 같은 꼴) ─────────────────────────────
const BOUNDS = [S2_START, S2_END];
const TABLES = BOUNDS.slice(0, -1).map((from, i) => makeTable(from, BOUNDS[i + 1]));
const lines = new Map(); // 단위 이름(조각 id 또는 '묶음/부분') → 주인 줄 [[해, 주인], …]
const layouts = []; // 나눈 조각 { name, ids, parts, restName, from, to, units }
const checkLine = (u, line) => {
  if (!Array.isArray(line) || !line.length || line.some((e, i) => !Array.isArray(e) || e.length !== 2 || !Number.isInteger(e[0]) || (i && e[0] <= line[i - 1][0]) || e[0] < S2_START || e[0] >= S2_END)) {
    throw new Error(`south-asia colonial: ${u}의 줄 ${JSON.stringify(line)} (해는 정수로 늘어나고 ${S2_START} 이상 ${S2_END} 전)`);
  }
};
// 주인 줄 적기: 단위마다 앞 줄 뒤에 잇는다(첫 줄이 아니면 첫 해가 앞 줄의 마지막 해보다 뒤)
const own = (units, line) => {
  for (const u of units) {
    checkLine(u, line);
    const prev = lines.get(u);
    if (prev && line[0][0] <= prev.at(-1)[0]) throw new Error(`south-asia colonial: ${u}의 이은 줄 첫 해 ${line[0][0]}가 앞 줄의 마지막 해 ${prev.at(-1)[0]} 이하`);
    lines.set(u, prev ? [...prev, ...line] : [...line]);
  }
};
// 나눈 조각: parts는 [[부분 이름, 칼선 도형], …](첫 부분 = 칼선1 안, 다음 = 칼선2 안 − 앞 칼선, …, 나머지 = 모든 칼선 밖). 반환 { 부분: '묶음/부분' }
const ownSplit = (name, ids, parts, restName, partLines = {}, { from = S2_START, to = S2_END } = {}) => {
  if (!BOUNDS.includes(from) || !BOUNDS.includes(to) || from >= to) throw new Error(`south-asia colonial: 나눈 조각 ${name}의 기간 [${from}, ${to})은 표 경계 해(${BOUNDS.join(', ')})여야 함`);
  for (const l of layouts) {
    const shared = l.ids.filter((id) => ids.includes(id));
    if (shared.length && l.from < to && from < l.to) throw new Error(`south-asia colonial: 나눈 조각 ${name}과 ${l.name}이 같은 기간에 조각 ${shared.join(', ')}를 함께 씀`);
  }
  const units = Object.fromEntries([...parts.map(([p]) => [p, `${name}/${p}`]), [restName, `${name}/${restName}`]]);
  layouts.push({ name, ids, parts, restName, from, to, units, out: null });
  for (const [p, line] of Object.entries(partLines)) {
    if (!units[p]) throw new Error(`south-asia colonial: 나눈 조각 ${name}에 없는 부분 ${p}`);
    own([units[p]], line);
  }
  return units;
};
// 한 표 기간의 줄(첫 해는 표의 첫 해). 그 표 첫 해에 주인이 정해지지 않았으면 멈춘다
const sliceLine = (u, line, FROM, TO) => {
  const head = line.filter(([y]) => y <= FROM).at(-1);
  if (!head) throw new Error(`south-asia colonial: ${u}의 줄이 ${line[0][0]}년에 시작해 ${FROM}~${TO - 1} 표 첫 해의 주인이 없음`);
  return [[FROM, head[1]], ...line.filter(([y]) => y > FROM && y < TO)];
};
// 모든 own·ownSplit 뒤에 표를 채운다(나머지 단위는 주인 null)
const fillTables = () => {
  const known = new Set([...SA.ids, ...layouts.flatMap((l) => Object.values(l.units))]);
  for (const u of lines.keys()) if (!known.has(u)) throw new Error(`south-asia colonial: 모르는 단위 ${u} (조각 id 또는 ownSplit이 돌려준 '묶음/부분')`);
  for (const T of TABLES) {
    const splitHere = new Set();
    for (const l of layouts.filter((x) => x.from <= T.FROM && T.TO <= x.to)) {
      l.out = l.out ? T.reuse(l.out) : T.split(l.name, l.ids, l.parts, l.restName);
      for (const u of Object.values(l.units)) T.own([u], lines.has(u) ? sliceLine(u, lines.get(u), T.FROM, T.TO) : [[T.FROM, null]]);
      for (const id of l.ids) splitHere.add(id);
    }
    // 통째 조각: 같은 줄끼리 묶어 한 번에(묶음은 도형에 영향 없음: 버전은 해마다 단위 목록으로 만든다)
    const groups = new Map();
    for (const id of SA.ids) {
      if (splitHere.has(id)) {
        const line = lines.get(id);
        if (line?.some(([y]) => y >= T.FROM && y < T.TO)) throw new Error(`south-asia colonial: 조각 ${id}는 ${T.FROM}~${T.TO - 1}에 나눈 조각이라 통째 줄을 적을 수 없음(단위 이름으로 적음)`);
        continue;
      }
      const sliced = lines.has(id) ? sliceLine(id, lines.get(id), T.FROM, T.TO) : [[T.FROM, null]];
      const key = JSON.stringify(sliced);
      if (!groups.has(key)) groups.set(key, { sliced, ids: [] });
      groups.get(key).ids.push(id);
    }
    for (const { sliced, ids } of groups.values()) T.own(T.whole(...ids), sliced);
  }
};

// 빈 땅 검사 구역에서 그해 통째로 뺄 다른 권역 도형(중국 쪽 청·중화민국 도형이 덮는 땅). 동 칸만 이 한 줄을 고친다(기본: 없음).
// 그 도형과 겹치는 조각 땅은 동 칸이 주인 null 부분으로 떼어 두고(modern.mjs의 CN_* 꼴), 여기서는 [from, to) 기간에 뺄 멀티폴리곤 목록을 돌려준다
const cnMinusOf = (from, to) => (from < S2_END ? [E_CN] : []); // 1757~1946 청·중화민국 도형의 이 권역 상자 안 모양(S2 동 칸 E_CN, 해마다 같음)

// ── S2 서 (파키스탄·카슈미르·펀자브·라지푸타나·구자라트·델리, 구현 S2-서): 칼선·상수·own 줄은 이 아래에, 최상위 이름은 W_ ──
// 그린 것: 두라니 제국의 남아시아 쪽(1757~1825), 시크 제국(1765~1848, 1799년 앞은 미슬 연합 시기), 잠무 카슈미르 주(1840~), 라다크 왕국, 치트랄, 바하왈푸르·하이르푸르·신드,
//   라지푸타나 큰 주 여섯과 동부 묶음, 쿠치·카티아와르 묶음·바로다, 펀자브 평원·산지 토후국 묶음, 칼라트 무리(S1 선 그대로)와 동인도 회사·영국령 인도로 넘어간 해.
// 칼선은 지금 지구·군 경계(읍 좌표로 안/밖을 확인)와 강(수틀레지·베아스·참발)을 어림한 손그림 선이다. 같은 조각을 나눈 칼선은 앞 부분이 먼저 가지므로(ownSplit) 뒤 칼선은 앞 칼선 쪽으로 넉넉히 그었다.
// 근거: 위키백과 en(Durrani Empire, Sikh Empire, Jammu and Kashmir (princely state), Khanate of Kalat, Talpur dynasty, Baroda State, Bahawalpur (princely state),
//   Punjab States Agency, Rajputana Agency, Kathiawar Agency, British Baluchistan, Chitral (princely state)). 넓이·기준 도시 판정은 결과 노트
import { I as W_I, box as W_box } from '../../lib.mjs';
import { versions as W_CN_VERSIONS } from '../china.mjs';
import { era as W_MODERN } from './modern.mjs';

// 나라 id (다른 칸이 글을 쓰는 항목 포함)
const W_CO = 'company-india';
const W_RAJ = 'british-raj';
const W_DUR = 'durrani-empire';
const W_SIKH = 'sikh-empire';
const W_JK = 'jammu-kashmir-state';
// 동인도 회사 땅이 된 해부터: 1858년 영국 정부 직할(영국령 인도)로 주인만 바뀜
const W_co = (year) => [[year, W_CO], [1858, W_RAJ]];
const W_ring = (pts) => [[...pts, pts[0]]];

// ── 중국 이음매: 라다크 동남부·히마찰 동북 가장자리(약 2,500 km²)는 동아시아 청(1757~1911)·중화민국(1912~) 도형이 덮는다 ──
// 그 도형은 바이트 그대로 두고, 이 칸 조각(IN-LA·IN-HP)에서 그 땅을 늘 주인 없음으로 뗀다(modern.mjs CN_* 꼴). 이 상자 안 모양은 1757~1946 모든 버전에서 같다(아래에서 확인)
const W_CN_BOX = W_box(72, 29, 82, 37.5);
const W_outer = (m) => m.map((poly) => [poly[0]]);
const W_CN = W_I(W_outer(W_CN_VERSIONS.qing.find(([from, to]) => from <= S2_START && S2_START < to)[2]), W_CN_BOX);
{
  const deg2 = (m) => m.reduce((s, p) => s + p.reduce((s2, r, k) => { let a = 0; for (let i = 0, j = r.length - 1; i < r.length; j = i++) a += (r[j][0] + r[i][0]) * (r[j][1] - r[i][1]); return s2 + (k ? -1 : 1) * Math.abs(a / 2); }, 0), 0);
  const land = SA.F('IN-LA', 'IN-HP');
  const base = W_I(land, W_CN);
  const seen = new Set();
  for (const id of ['qing', 'roc']) {
    for (const [from, to, geom] of W_CN_VERSIONS[id]) {
      if ((to ?? 9999) <= S2_START || from >= S2_END || seen.has(geom)) continue;
      seen.add(geom);
      const here = W_I(land, W_I(W_outer(geom), W_CN_BOX));
      const diff = deg2(D(here, base)) + deg2(D(base, here));
      if (diff > 1e-6) throw new Error(`south-asia colonial: ${id} ${from}년 도형이 라다크·히마찰 쪽에서 1757년 청 도형과 약 ${Math.round(diff * 1e4)}km² 다름 (중국 이음매 부분을 해마다 나눠야 함)`);
    }
  }
}

