// 비카네르 주(지금 비카네르·추루·강가나가르·하누만가르 지구): 남쪽은 노카·수잔가르 안, 나고르·라드누(조드푸르 주) 밖, 동쪽은 추루·사둘푸르 안, 파테푸르·만다와·필라니(셰카와티, 자이푸르 주) 밖
