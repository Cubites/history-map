// 중국 도형으로 자른 자리에 남는 넓이 0에 가까운 부스러기 폴리곤(약 0.001 km² 미만, 라다크 쪽 실효 지배선 꼭짓점)은 뺀다(쓰기 반올림 뒤 넓이 0 조각이 됨)
const dropCrumbs = (m) => { const out = m.filter((poly) => deg2([poly]) > 1e-7); return out.length === m.length ? m : out; };
